def family_colors(keys):
    """按黄金角分配色相，保证 13 个家族都明显可分。"""
    out = {}
    for i, k in enumerate(keys):
        h = ((i * 137.508) + 18) % 360 / 360.0
        r, g, b = colorsys.hls_to_rgb(h, 0.63, 0.62)
        out[k] = "#%02x%02x%02x" % (int(r * 255), int(g * 255), int(b * 255))
    return out
